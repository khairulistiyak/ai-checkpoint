const path = require('path');

function suggestCanonicalFileName(funcName, fileA, fileB) {
  const base = funcName.replace(/([A-Z])/g, '-$1').toLowerCase().replace(/^-/, '');
  if (base.includes('walk') || base.includes('file')) return 'packages/core/file-walker.js';
  if (base.includes('date') || base.includes('time')) return 'packages/core/date-formatter.js';
  if (base.includes('syntax') || base.includes('balance') || base.includes('bracket')) return 'packages/core/syntax-utils.js';
  if (base.includes('sanitize') || base.includes('escape')) return 'packages/core/sanitizer.js';
  const dir = path.dirname(fileA);
  return path.join(dir.includes('dashboard') ? 'dashboard/src/utils' : 'packages/core', `${base}.js`);
}

function generateSharedModuleCode(funcA, isEsm = false) {
  const cleanBody = funcA.body.trim();
  const signature = `function ${funcA.name}(${funcA.params})`;
  const header = `// Auto-generated by DRY Guardian\n// Shared extraction for ${funcA.name}\n\n`;
  const code = cleanBody.startsWith('function') || cleanBody.startsWith('const') ? cleanBody : `${signature} {\n  ${cleanBody}\n}`;
  const exportStmt = isEsm ? `\nexport { ${funcA.name} };\n` : `\nmodule.exports = { ${funcA.name} };\n`;
  return header + code + exportStmt;
}

function generateImportSnippet(targetFile, callerFile, funcName) {
  const isEsm = callerFile.includes('dashboard/src');
  const targetPath = './' + path.relative(path.dirname(callerFile), targetFile).replace(/\\/g, '/');
  if (isEsm) {
    return `import { ${funcName} } from '${targetPath}';`;
  }
  return `const { ${funcName} } = require('${targetPath}');`;
}

function generateRefactorProposal(duplicatePair) {
  const { funcA, funcB, type, score } = duplicatePair;
  const targetFile = suggestCanonicalFileName(funcA.name, funcA.file, funcB.file);
  const isEsm = targetFile.includes('dashboard/src');
  const sharedCode = generateSharedModuleCode(funcA, isEsm);
  const importA = generateImportSnippet(targetFile, funcA.file, funcA.name);
  const importB = generateImportSnippet(targetFile, funcB.file, funcB.name);

  const diffA = `- // Duplicate ${funcA.name} definition\n- ${funcA.body.slice(0, 100)}...\n+ ${importA}`;
  const diffB = `- // Duplicate ${funcB.name} definition\n- ${funcB.body.slice(0, 100)}...\n+ ${importB}`;

  return {
    funcA: { name: funcA.name, file: funcA.file, line: funcA.line },
    funcB: { name: funcB.name, file: funcB.file, line: funcB.line },
    similarity: score,
    type,
    targetFile,
    proposedModuleContent: sharedCode,
    callerA: { file: funcA.file, line: funcA.line, importSnippet: importA, diff: diffA },
    callerB: { file: funcB.file, line: funcB.line, importSnippet: importB, diff: diffB },
    guidance: `Extract '${funcA.name}' to '${targetFile}' and replace local copies with canonical imports.`
  };
}

module.exports = { generateRefactorProposal, suggestCanonicalFileName, generateSharedModuleCode };
